  const ORDER = ['en', 'zh-Hant', 'zh-Hans', 'ja', 'ko', 'es', 'fr', 'de', 'pt', 'ru',
    'id', 'vi', 'th', 'hi', 'tr', 'it', 'pl', 'ar'];
  const RTL = ['ar']; // 右到左語言
  const KEY = 'pupdoku_lang';

  function detect() {
    const list = (navigator.languages && navigator.languages.length)
      ? navigator.languages : [navigator.language || 'en'];
    for (const raw of list) {
      const low = String(raw).toLowerCase();
      if (low.startsWith('zh')) {
        return (low.includes('hant') || low.includes('tw') || low.includes('hk') || low.includes('mo'))
          ? 'zh-Hant' : 'zh-Hans';
      }
      const two = low.slice(0, 2);
      if (ORDER.includes(two)) return two;
    }
    return 'en';
  }

  const api = {
    order: ORDER,
    lang: 'en',
    name(code) { return (L[code] || L.en).name; },
    t(key, params) {
      const dict = L[api.lang] || L.en;
      let s = (dict[key] != null ? dict[key] : (L.en[key] != null ? L.en[key] : key));
      if (params) for (const k in params) s = s.split('{' + k + '}').join(params[k]);
      return s;
    },
    setLang(code) {
      if (!L[code]) code = 'en';
      api.lang = code;
      try { localStorage.setItem(KEY, code); } catch (e) { /* ignore */ }
      api.apply();
    },
    init() {
      let saved = null;
      try { saved = localStorage.getItem(KEY); } catch (e) { /* ignore */ }
      const urlLang = new URLSearchParams(location.search).get('lang');
      // 優先序：?lang= > 頁面自帶語言（各語言靜態頁）> 上次選擇 > 瀏覽器偵測
      const pageLang = (typeof window !== 'undefined' && window.__WD_LANG) || null;
      api.lang = (urlLang && L[urlLang]) ? urlLang
        : (pageLang && L[pageLang]) ? pageLang
          : (saved && L[saved]) ? saved
            : detect();
      api.apply();
    },
    // 套用所有帶 data-i18n / data-i18n-html 的靜態元素
    apply() {
      document.documentElement.lang = api.lang;
      document.documentElement.dir = RTL.includes(api.lang) ? 'rtl' : 'ltr';
      document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = api.t(el.dataset.i18n); });
      document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = api.t(el.dataset.i18nHtml); });
      if (typeof api.onApply === 'function') api.onApply();
    },
  };

  global.I18N = api;
